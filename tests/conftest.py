def index_repo(path: str, name: str = "r", mode: str = "full", kind: str = "user") -> int:
    from app.db.session import session_scope
    from app.indexing.indexer import create_job, run_indexing_job
    from app.models import Repository

    with session_scope() as s:
        repo = s.query(Repository).filter_by(root_path=str(Path(path).resolve())).one_or_none()
        if repo is None:
            repo = Repository(name=name, root_path=str(Path(path).resolve()), kind=kind)
            s.add(repo)
            s.flush()
        job = create_job(s, repo, mode)
        rid, jid = repo.id, job.id
    res = run_indexing_job(jid)
    assert res["status"] == "COMPLETED", res
    return rid


def write_tree(root: Path, files: dict[str, str]) -> Path:
    for rel, content in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    return root


def tree_hashes(root: Path) -> dict[str, str]:
    import hashlib

    return {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(root.rglob("*")) if p.is_file()}


